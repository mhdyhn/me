#!/usr/bin/env node
/**
 * Engine pipeline check. Loads the engine through Vite's SSR loader (so the TypeScript
 * sources run as they do in the app), validates every exercise, checks that each model
 * file exists and is a binary glTF, and writes docs/engine/STATUS.md.
 *
 * Exit code 1 when any configuration is rejected or any asset is missing.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

/** The initial library named in the brief, with the catalogue id that covers each entry. */
const INITIAL_LIBRARY = [
  ['Barbell Bench Press', 'barbell-bench-press'],
  ['Incline Dumbbell Press', 'incline-dumbbell-press'],
  ['Dumbbell Shoulder Press', 'shoulder-press'],
  ['Cable Chest Fly', 'cable-fly'],
  ['Dumbbell Lateral Raise', 'lateral-raise'],
  ['Cable Triceps Pushdown', 'cable-triceps-pushdown'],
  ['Overhead Cable Triceps Extension', 'overhead-cable-triceps-extension'],
  ['Lat Pulldown', 'lat-pulldown'],
  ['Seated Cable Row', 'seated-cable-row'],
  ['One-Arm Dumbbell Row', 'one-arm-dumbbell-row'],
  ['Barbell Squat', 'barbell-squat'],
  ['Leg Press', 'leg-press'],
  ['Leg Extension', 'leg-extension'],
  ['Leg Curl', 'leg-curl'],
  ['Romanian Deadlift', 'romanian-deadlift'],
  ['Bulgarian Split Squat', 'bulgarian-split-squat'],
  ['Standing Calf Raise', 'standing-calf-raise'],
  ['Seated Calf Raise', 'seated-calf-raise'],
  ['Dumbbell Biceps Curl', 'dumbbell-biceps-curl'],
  ['Incline Dumbbell Curl', 'incline-dumbbell-curl'],
];

const server = await createServer({
  root,
  configFile: false,
  logLevel: 'error',
  server: { middlewareMode: true, hmr: false },
  appType: 'custom',
});

let failures = 0;
try {
  const engine = await server.ssrLoadModule('/src/engine/index.ts');
  const catalog = await server.ssrLoadModule('/src/engine/catalog.ts');
  const motionLib = await server.ssrLoadModule('/src/motion/library.ts');

  const configs = catalog.appExerciseConfigs();
  const registry = engine.createRegistry(configs, { motionIds: catalog.appMotionIds() });
  const rejected = registry.report.rejected;
  failures += rejected.length;

  const rows = [];
  for (const config of configs) {
    const modelPath = join(root, 'public', config.model.asset);
    let asset = 'ok';
    if (!existsSync(modelPath)) {
      asset = 'missing file';
      failures += 1;
    } else {
      const magic = readFileSync(modelPath).subarray(0, 4).toString('ascii');
      if (magic !== 'glTF') {
        asset = 'not a binary glTF';
        failures += 1;
      }
    }
    const mapping = engine.mapMuscles(config);
    const motion = motionLib.motions[config.motion.id];
    rows.push({
      id: config.id,
      name: config.name.en,
      keys: motion ? motion.keys.length : 0,
      seconds: config.motion.durationSeconds,
      primary: mapping.primary.map((item) => item.label.en).join(', '),
      secondary: mapping.secondary.map((item) => item.label.en).join(', '),
      unpainted: mapping.unmapped.map((item) => item.en).join(', '),
      equipment: config.equipment.map((item) => item.en).join(', '),
      status: config.validation.status,
      asset,
    });
  }

  const ids = new Set(configs.map((config) => config.id));
  const libraryRows = INITIAL_LIBRARY.map(([name, id]) => ({
    name,
    id,
    present: id !== null && ids.has(id),
  }));

  // The brief's calendar is Tehran time, so the report date follows that zone.
  const today = new Date().toLocaleDateString('en-CA', { timeZone: 'Asia/Tehran' });
  const lines = [
    '# Engine status',
    '',
    `Generated by \`npm run verify:engine\` on ${today}. Edit the source, not this file.`,
    '',
    '## Summary',
    '',
    `- Exercise configurations: **${configs.length}**; accepted by the registry: **${registry.report.accepted.length}**; rejected: **${rejected.length}**.`,
    `- Model file check: **${rows.filter((row) => row.asset === 'ok').length} of ${rows.length}** configurations point to a valid binary glTF.`,
    `- Validation status: ${countBy(rows, 'status')}.`,
    `- Initial library in the brief: **${libraryRows.filter((row) => row.present).length} of ${libraryRows.length}** present.`,
    '',
    '## Initial library (from the brief)',
    '',
    '| Brief entry | Catalogue id | Status |',
    '| --- | --- | --- |',
    ...libraryRows.map((row) => `| ${row.name} | ${row.id ?? '—'} | ${row.present ? 'present, unverified' : 'missing: no movement written for it'} |`),
    '',
    '## Exercises',
    '',
    '| Id | Name | Loop keys | Loop length (s) | Primary muscles | Secondary muscles | Not painted | Status | Model |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| ${row.id} | ${row.name} | ${row.keys} | ${row.seconds} | ${row.primary} | ${row.secondary || '—'} | ${row.unpainted || '—'} | ${row.status} | ${row.asset} |`),
    '',
    '## Rejected configurations',
    '',
    rejected.length === 0 ? 'None.' : rejected.map((item) => `- \`${item.id}\`: ${item.issues.map((issue) => `${issue.path} ${issue.message}`).join('; ')}`).join('\n'),
    '',
    '## Equipment per exercise',
    '',
    ...rows.map((row) => `- **${row.name}**: ${row.equipment}`),
    '',
  ];
  writeFileSync(join(root, 'docs', 'engine', 'STATUS.md'), lines.join('\n'));

  console.log(`engine: ${registry.report.accepted.length}/${configs.length} exercises accepted`);
  console.log(`engine: initial library ${libraryRows.filter((row) => row.present).length}/${libraryRows.length} present`);
  console.log(`engine: wrote docs/engine/STATUS.md`);
  if (failures > 0) {
    console.error(`engine: ${failures} problem(s) found`);
  }
} finally {
  await server.close();
}
process.exit(failures > 0 ? 1 : 0);

function countBy(rows, key) {
  const counts = {};
  for (const row of rows) counts[row[key]] = (counts[row[key]] ?? 0) + 1;
  return Object.entries(counts).map(([value, count]) => `${value}: ${count}`).join(', ');
}
